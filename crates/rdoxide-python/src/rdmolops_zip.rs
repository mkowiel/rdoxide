//! `molzip` of `rdkit.Chem.rdmolops` (upstream `GraphMol/Wrap/MolOps.cpp`):
//! `MolzipLabel`, `MolzipParams`, `molzip` and `molzipFragments`.

use std::collections::BTreeMap;

use pyo3::exceptions::{PyAttributeError, PyValueError};
use pyo3::prelude::*;
use pyo3::types::{PyDict, PyTuple};
use rdoxide::graphmol::chem_transforms::{
    MolzipLabel, MolzipParams, molzip, molzip_fragments, molzip_row, molzip_single,
};

use crate::enums::{add_enum, to_py};
use crate::errors::{IntoPyResult, argument_error, boost_type_name};
use crate::mol::PyMol;
use crate::rdmolfiles_write::Args;

const LABELS: [(&str, i64); 4] = [
    ("AtomMapNumber", 0),
    ("Isotope", 1),
    ("FragmentOnBonds", 2),
    ("AtomType", 3),
];

/// Parameters controlling how to zip molecules together
///
///   OPTIONS:
///       label : set the MolzipLabel option [default MolzipLabel.AtomMapNumber]
///
///   MolzipLabel.AtomMapNumber: atom maps are on dummy atoms, zip together the corresponding
///      attached atoms, i.e.  zip 'C[*:1]' 'N[*:1]' results in 'CN'
///
///   MolzipLabel.Isotope: isotope labels are on dummy atoms, zip together the corresponding
///      attached atoms, i.e.  zip 'C[1*]' 'N[1*]' results in 'CN'
///
///   MolzipLabel.FragmentOnBonds: zip together molecules generated by fragment on bonds.
///     Note the atom indices cannot change or be reordered from the output of fragmentOnBonds
///
///   MolzipLabel.AtomTypes: choose the atom types to act as matching dummy atoms.
///     i.e.  'C[V]' and 'N[Xe]' with atoms pairs [('V', 'Xe')] results in 'CN'
#[pyclass(
    name = "MolzipParams",
    module = "rdkit.Chem.rdmolops",
    dict,
    skip_from_py_object
)]
#[derive(Clone, Debug, Default)]
pub struct PyMolzipParams {
    params: MolzipParams,
}

#[pymethods]
impl PyMolzipParams {
    #[new]
    fn py_new() -> Self {
        Self::default()
    }

    /// Set the atom labeling system to zip together
    #[getter]
    fn label(&self, py: Python<'_>) -> PyResult<Py<PyAny>> {
        to_py(py, "MolzipLabel", self.params.label as i64)
    }

    /// If true (default) enforce valences after zipping
    /// Setting this to false allows assembling chemically incorrect fragments.
    #[getter(enforceValenceRules)]
    fn enforce_valence_rules(&self) -> bool {
        self.params.enforce_valence_rules
    }

    /// If true will add depiction coordinates to input molecules and
    /// zipped molecule (for molzipFragments only)
    #[getter(generateCoordinates)]
    fn generate_coordinates(&self) -> bool {
        self.params.generate_coordinates
    }

    /// if true and the input fragments have coordinates, the fragments
    /// will be aligned along connection vectors in the output molecule
    #[getter(alignCoordinates)]
    fn align_coordinates(&self) -> bool {
        self.params.align_coordinates
    }

    /// Set the atom symbols used to zip mols together when using AtomType labeling
    #[pyo3(name = "setAtomSymbols", signature = (symbols))]
    fn set_atom_symbols(&mut self, symbols: Option<&Bound<'_, PyAny>>) -> PyResult<()> {
        self.params.atom_symbols.clear();
        if let Some(symbols) = symbols.filter(|s| s.is_truthy().unwrap_or(false)) {
            for i in 0..symbols.len()? {
                self.params
                    .atom_symbols
                    .push(symbols.get_item(i)?.extract()?);
            }
        }
        Ok(())
    }

    /// Only the documented attributes can be set (upstream's `safeSetattr`);
    /// other attributes of the class (the methods) are shadowed on the
    /// instance, as `object.__setattr__` does.
    fn __setattr__(slf: &Bound<'_, Self>, name: &str, value: &Bound<'_, PyAny>) -> PyResult<()> {
        let py = slf.py();
        let mut this = slf.borrow_mut();
        match name {
            "label" => {
                let label_class = to_py(py, "MolzipLabel", 0)?.bind(py).get_type();
                let label = value
                    .is_instance(&label_class)?
                    .then(|| value.extract::<u8>().ok().and_then(MolzipLabel::from_u8))
                    .flatten()
                    .ok_or_else(|| {
                        argument_error(
                            py,
                            "None",
                            &["MolzipParams".to_string(), boost_type_name(value)],
                            "None(RDKit::MolzipParams {lvalue}, RDKit::MolzipLabel)",
                        )
                    })?;
                this.params.label = label;
            }
            "enforceValenceRules" => this.params.enforce_valence_rules = value.is_truthy()?,
            "generateCoordinates" => this.params.generate_coordinates = value.is_truthy()?,
            "alignCoordinates" => this.params.align_coordinates = value.is_truthy()?,
            _ if py.get_type::<Self>().hasattr(name)? => {
                drop(this);
                py.import("builtins")?
                    .getattr("object")?
                    .call_method1("__setattr__", (slf, name, value))?;
            }
            _ => {
                return Err(PyAttributeError::new_err(format!(
                    "Cannot set unknown attribute '{name}'"
                )));
            }
        }
        Ok(())
    }
}

const ROW_SIGNATURE: &str = "molzip(boost::python::dict row, RDKit::MolzipParams params=<rdkit.Chem.rdmolops.MolzipParams object at 0x0>)";
const SINGLE_SIGNATURE: &str = "molzip(RDKit::ROMol a, RDKit::MolzipParams params=<rdkit.Chem.rdmolops.MolzipParams object at 0x0>)";
const PAIR_SIGNATURE: &str = "molzip(RDKit::ROMol a, RDKit::ROMol b, RDKit::MolzipParams params=<rdkit.Chem.rdmolops.MolzipParams object at 0x0>)";

fn params_arg(arg: Option<Bound<'_, PyAny>>) -> Option<PyResult<MolzipParams>> {
    match arg {
        None => Some(Ok(MolzipParams::default())),
        Some(p) => p
            .cast::<PyMolzipParams>()
            .ok()
            .map(|p| Ok(p.borrow().params.clone())),
    }
}

/// zip together two molecules using the given matching parameters, or the
/// labelled atoms within a combined molecule, or an R group row (a dict of
/// molecules with a `Core`)
#[pyfunction]
#[pyo3(name = "molzip", signature = (*args, **kwargs))]
fn py_molzip(
    py: Python<'_>,
    args: &Bound<'_, PyTuple>,
    kwargs: Option<&Bound<'_, PyDict>>,
) -> PyResult<Option<PyMol>> {
    let a = Args {
        name: "molzip",
        args,
        kwargs,
    };
    let bad_call = || {
        let got: Vec<String> = args.iter().map(|o| boost_type_name(&o)).collect();
        argument_error(
            py,
            "molzip",
            &got,
            &format!("{ROW_SIGNATURE}\n    {SINGLE_SIGNATURE}\n    {PAIR_SIGNATURE}"),
        )
    };
    let first = a.get(0, "a")?.or(a.get(0, "row")?);
    let Some(first) = first else {
        return Err(bad_call());
    };
    if let Ok(row) = first.cast::<PyDict>() {
        let Some(params) = params_arg(a.get(1, "params")?) else {
            return Err(bad_call());
        };
        let params = params?;
        let mut rows = BTreeMap::new();
        for (key, value) in row.iter() {
            match (key.extract::<String>(), value.cast::<PyMol>()) {
                (Ok(key), Ok(mol)) => {
                    rows.insert(key, mol.borrow().mol.clone());
                }
                _ => {
                    return Err(PyValueError::new_err(
                        "Unable to retrieve rgroup key and molecule from dictionary",
                    ));
                }
            }
        }
        let res = py.detach(|| molzip_row(&mut rows, &params)).py()?;
        return Ok(res.map(|mol| PyMol { mol }));
    }
    let Ok(first) = first.cast::<PyMol>() else {
        return Err(bad_call());
    };
    let second = a.get(1, "b")?;
    let (second_mol, params_obj) = match second {
        Some(s) if s.cast::<PyMol>().is_ok() => (Some(s), a.get(2, "params")?),
        other => (None, other.or(a.get(1, "params")?)),
    };
    let Some(params) = params_arg(params_obj) else {
        return Err(bad_call());
    };
    let params = params?;
    let first = first.borrow();
    let res = match second_mol {
        Some(second) => {
            let second = second.cast::<PyMol>()?.borrow();
            let (m1, m2) = (&first.mol, &second.mol);
            py.detach(|| molzip(m1, m2, &params)).py()?
        }
        None => {
            let m1 = &first.mol;
            py.detach(|| molzip_single(m1, &params)).py()?
        }
    };
    Ok(res.map(|mol| PyMol { mol }))
}

/// zip together multiple molecules from an R group decomposition
/// using the given matching parameters.  The first molecule in the list
/// must be the core
#[pyfunction]
#[pyo3(name = "molzipFragments", signature = (mols, params = None))]
fn py_molzip_fragments(
    py: Python<'_>,
    mols: &Bound<'_, PyAny>,
    params: Option<PyRef<'_, PyMolzipParams>>,
) -> PyResult<Option<PyMol>> {
    let params = params.map(|p| p.params.clone()).unwrap_or_default();
    if !mols.is_truthy()? {
        return Ok(None);
    }
    let handles = mols
        .try_iter()?
        .map(|m| Ok(m?.cast_into::<PyMol>()?))
        .collect::<PyResult<Vec<_>>>()?;
    let mut copies: Vec<_> = handles.iter().map(|h| h.borrow().mol.clone()).collect();
    let res = py.detach(|| molzip_fragments(&mut copies, &params)).py()?;
    if params.generate_coordinates {
        // the pieces get the coordinates of the zipped molecule
        for (handle, copy) in handles.iter().zip(copies) {
            handle.borrow_mut().mol = copy;
        }
    }
    Ok(res.map(|mol| PyMol { mol }))
}

pub fn add(m: &Bound<'_, PyModule>) -> PyResult<()> {
    add_enum(m, "MolzipLabel", &LABELS, None)?;
    m.add_class::<PyMolzipParams>()?;
    m.add_function(wrap_pyfunction!(py_molzip, m)?)?;
    m.add_function(wrap_pyfunction!(py_molzip_fragments, m)?)?;
    Ok(())
}
