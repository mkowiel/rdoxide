//! Gaussian cube files (`writeToCubeStream`, `readFromCubeStream` ...).

use std::fmt::Write as _;

use crate::geometry::Point3D;
use crate::geometry::grid::UniformRealValueGrid3D;
use crate::graphmol::atom::Atom;
use crate::graphmol::conformer::Conformer;
use crate::graphmol::romol::{ROMol, RWMol};
use crate::rdgeneral::strings::format_g;
use crate::{RDKitError, Result};

const BOHR: f64 = 0.529177249;

/// A value left-aligned in 20 columns (`std::setw(20)` with
/// `std::ios::left`).
fn field(out: &mut String, text: &str) {
    let _ = write!(out, "{text:<20}");
}

fn g(x: f64) -> String {
    format_g(x, 6)
}

/// `writeToCubeStream`: the text of the cube file of the grid and, if
/// given, the conformer of the molecule.
pub fn write_to_cube_stream(
    grd: &UniformRealValueGrid3D,
    mol: Option<&ROMol>,
    conf_id: i32,
) -> Result<String> {
    let (nx, ny, nz) = (grd.num_x(), grd.num_y(), grd.num_z());
    let spacing = grd.spacing() / BOHR;
    let off = grd.offset();
    let off = Point3D::new(off.x / BOHR, off.y / BOHR, off.z / BOHR);
    let n_atoms = mol.map_or(0, ROMol::num_atoms);
    let mut out =
        String::from("Gaussian cube format generated by RDKit\n*************************\n");
    for t in [n_atoms.to_string(), g(off.x), g(off.y), g(off.z)] {
        field(&mut out, &t);
    }
    out.push('\n');
    for row in [
        [nx.to_string(), g(spacing), "0".into(), "0".into()],
        [ny.to_string(), "0".into(), g(spacing), "0".into()],
        [nz.to_string(), "0".into(), "0".into(), g(spacing)],
    ] {
        for t in &row {
            field(&mut out, t);
        }
        out.push('\n');
    }
    if let Some(mol) = mol {
        // (fails for a missing conformer)
        let conf = mol.conformer(conf_id)?;
        for i in 0..mol.num_atoms() {
            let p = conf.atom_pos(i)?;
            let z = mol.atom(i).atomic_num().to_string();
            for t in [z.clone(), z, g(p.x / BOHR), g(p.y / BOHR), g(p.z / BOHR)] {
                field(&mut out, &t);
            }
            out.push('\n');
        }
    }
    for xi in 0..nx {
        for yi in 0..ny {
            for zi in 0..nz {
                let v = grd.val(grd.grid_index(xi, yi, zi) as u32)?;
                field(&mut out, &g(v));
                if (zi + 1) % 8 == 0 {
                    out.push('\n');
                }
            }
            out.push('\n');
        }
        out.push('\n');
    }
    Ok(out)
}

/// `writeToCubeFile`
pub fn write_to_cube_file(
    grd: &UniformRealValueGrid3D,
    filename: &str,
    mol: Option<&ROMol>,
    conf_id: i32,
) -> Result<()> {
    let text = write_to_cube_stream(grd, mol, conf_id)?;
    std::fs::write(filename, text)
        .map_err(|_| RDKitError::BadFile(format!("Bad output file {filename}")))
}

/// `readFromCubeStream`: the grid and the molecule (atoms and coordinates
/// only) of the cube file, if it has one.
pub fn read_from_cube_stream(text: &str) -> Result<(UniformRealValueGrid3D, Option<RWMol>)> {
    // two comment lines, then whitespace separated numbers
    let mut rest = text;
    for _ in 0..2 {
        rest = rest.split_once('\n').map_or("", |(_, r)| r);
    }
    let mut tokens = rest.split_whitespace();
    let mut next = |what: &str| -> Result<&str> {
        tokens
            .next()
            .ok_or_else(|| RDKitError::FileParse(format!("Unexpected end of cube data ({what})")))
    };
    fn num<T: std::str::FromStr>(s: &str) -> Result<T> {
        s.parse()
            .map_err(|_| RDKitError::FileParse(format!("Cannot parse '{s}' in cube data")))
    }
    let n_atoms: i32 = num(next("atom count")?)?;
    let (x, y, z): (f64, f64, f64) = (
        num(next("offset")?)?,
        num(next("offset")?)?,
        num(next("offset")?)?,
    );
    let offset = Point3D::new(x * BOHR, y * BOHR, z * BOHR);
    let dim_x: i32 = num(next("dimension")?)?;
    let spacing_x: f64 = num(next("spacing")?)?;
    next("spacing")?;
    next("spacing")?;
    let dim_y: i32 = num(next("dimension")?)?;
    next("spacing")?;
    let spacing_y: f64 = num(next("spacing")?)?;
    next("spacing")?;
    let dim_z: i32 = num(next("dimension")?)?;
    next("spacing")?;
    next("spacing")?;
    let spacing_z: f64 = num(next("spacing")?)?;
    if (spacing_x - spacing_y).abs() > 0.0001 || (spacing_x - spacing_z).abs() > 0.0001 {
        return Err(RDKitError::FileParse(
            "Same spacing in all directions needed".into(),
        ));
    }
    let spacing = spacing_x * BOHR;
    let mut grd = UniformRealValueGrid3D::new(
        spacing * f64::from(dim_x),
        spacing * f64::from(dim_y),
        spacing * f64::from(dim_z),
        spacing,
        Some(offset),
    )?;
    let mut molecule = None;
    if n_atoms != 0 {
        let mut mol = RWMol::new();
        let mut conf = Conformer::new(n_atoms as usize);
        for i in 0..n_atoms as u32 {
            let atom_num: i32 = num(next("atom")?)?;
            next("atom")?;
            let (x, y, z): (f64, f64, f64) = (
                num(next("atom")?)?,
                num(next("atom")?)?,
                num(next("atom")?)?,
            );
            mol.add_atom(Atom::new(atom_num as u32), true);
            conf.set_atom_pos(i, Point3D::new(x * BOHR, y * BOHR, z * BOHR))?;
        }
        mol.add_conformer(conf, false)?;
        molecule = Some(mol);
    }
    for xi in 0..dim_x as u32 {
        for yi in 0..dim_y as u32 {
            for zi in 0..dim_z as u32 {
                let v: f64 = num(next("value")?)?;
                grd.set_val(grd.grid_index(xi, yi, zi) as u32, v)?;
            }
        }
    }
    Ok((grd, molecule))
}

/// `readFromCubeFile`
pub fn read_from_cube_file(filename: &str) -> Result<(UniformRealValueGrid3D, Option<RWMol>)> {
    let bytes = std::fs::read(filename)
        .map_err(|_| RDKitError::BadFile(format!("Bad input file {filename}")))?;
    read_from_cube_stream(&String::from_utf8_lossy(&bytes))
}
