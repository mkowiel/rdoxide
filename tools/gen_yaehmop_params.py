#!/usr/bin/env python3
"""Generate crates/rdoxide/src/external/yaehmop/params_data.rs from YAeHMOP's tightbind/eht_parms.h
(the default extended Hueckel parameter table compiled into the library).

usage: gen_yaehmop_params.py PATH/TO/eht_parms.h"""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1]).read_text().splitlines()
rows = []
for line in src:
    line = line.strip()
    m = re.match(r'^"([^"]+)"\s*,?\s*$', line)
    if not m or line.startswith("//"):
        continue
    text = m.group(1)
    if text == "END":
        break
    f = text.split()
    if len(f) != 11:
        continue  # malformed upstream row (No): the C parser cannot read it either
    sym, atnum, nval, nzeta, nquant, ang = f[0], *map(int, f[1:5]), f[5]
    hii, e1, e2, c1, c2 = f[6:11]
    rows.append((sym, atnum, nval, nzeta, nquant, ang, hii, e1, e2, c1, c2))

out = ["// generated by tools/gen_yaehmop_params.py from YAeHMOP tightbind/eht_parms.h; do not edit",
       "",
       "use super::params::Row;",
       "",
       "pub(super) static ROWS: &[Row] = &["]
for r in rows:
    sym, atnum, nval, nzeta, nquant, ang, hii, e1, e2, c1, c2 = r
    fl = lambda s: s if ("." in s or "e" in s) else s + ".0"
    out.append(f'    Row {{ sym: "{sym}", atnum: {atnum}, nval: {nval}, nzeta: {nzeta}, nquant: {nquant}, ang: b\'{ang}\', '
               f'hii: {fl(hii)}, exp1: {fl(e1)}, exp2: {fl(e2)}, c1: {fl(c1)}, c2: {fl(c2)} }},')
out.append("];")
Path("crates/rdoxide/src/external/yaehmop/params_data.rs").write_text("\n".join(out) + "\n")
print(len(rows), "rows")
