#!/usr/bin/env python3
"""Generate crates/rdoxide/src/graphmol/file_parsers/sequence_tables.rs from
upstream Code/GraphMol/FileParsers/SequenceParsers.cpp and SequenceWriters.cpp.

Upstream builds each residue with straight-line C++ (`CreateAAAtom`,
`CreateAABond`, ...). The statements are regular, so they are translated
one-to-one into `Op` tables that `sequence_parser.rs` interprets. Run
`cargo fmt` afterwards."""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "upstream/rdkit/Code/GraphMol/FileParsers/SequenceParsers.cpp"
WRITER_SRC = ROOT / "upstream/rdkit/Code/GraphMol/FileParsers/SequenceWriters.cpp"
OUT = ROOT / "crates/rdoxide/src/graphmol/file_parsers/sequence_tables.rs"

SLOT = r"(r[123]|atom\[\d+\])"
STATEMENT = re.compile(
    rf"CreateAABackbone\(mol, r1, r2, (?P<bb>atom\[\d+\]), info, (?P<ld>-?\d+)\)"
    rf"|(?P<dst>{SLOT}) = CreateAAAtom\(mol, \"(?P<name>[^\"]*)\", info\)"
    rf"|CreateAABond\(mol, (?P<b1>{SLOT}), (?P<b2>{SLOT}), (?P<order>\d)\)"
    r"|info\.setIsHeteroAtom\((?P<het>true|false)\)"
    rf"|(?P<chi>{SLOT})->setChiralTag\(Atom::CHI_TETRAHEDRAL_(?P<tag>CW|CCW)\)"
)


def slot(text: str) -> str:
    if text.startswith("r"):
        return "R" + text[1]
    return f"A({text[5:-1]})"


def ops(block: str) -> list[str]:
    out = []
    for m in STATEMENT.finditer(block):
        if m["bb"]:
            assert m["bb"] == "atom[0]"
            out.append(f"Backbone({m['ld']})")
        elif m["dst"]:
            out.append(f'Atom({slot(m["dst"])}, "{m["name"]}")')
        elif m["b1"]:
            out.append(f"Bond({slot(m['b1'])}, {slot(m['b2'])}, {m['order']})")
        elif m["het"]:
            out.append(f"Hetero({m['het']})")
        else:
            out.append(f"Chiral({slot(m['chi'])}, {m['tag']})")
    return out


def region(text: str, start: str, end: str) -> str:
    a = text.index(start)
    return text[a : text.index(end, a)]


def helm_peptide_monomers(text: str) -> list[tuple[str, str]]:
    """The (monomer id, residue code) pairs of `LookupHELMPeptideMonomer`:
    nested switches on the characters of the id with `ptr[n] == '\\0'` ends."""
    body = region(text, "static const char *LookupHELMPeptideMonomer", "static const char *ParseHELMPeptide")
    pairs = []
    top = nested = None
    pending = None
    for line in body.splitlines():
        indent = len(line) - len(line.lstrip())
        if m := re.match(r"case '(\w)':", line.strip()):
            if indent == 4:
                top, nested = m[1], None
            else:
                nested = m[1]
        elif m := re.match(r"if \((.*)\) \{", line.strip()):
            pending = m[1]
        elif m := re.match(r'return "(\w+)";', line.strip()):
            chars = re.findall(r"ptr\[(\d)\] == '(\w)'", pending)
            ident = (top or "") + (nested or "") + "".join(c for _, c in sorted(chars))
            pairs.append((ident, m[1]))
    return pairs


def emit(items: list[str]) -> str:
    return "\n".join(f"        {i}," for i in items)


def main() -> None:
    text = SRC.read_text()

    aa = region(text, "static void CreateAminoAcid", "static RWMol *AASequenceToMol")
    parts = re.split(r'!strcmp\(aa, "(\w+)"\)\)', aa)
    residues = []
    for name, body in zip(parts[1::2], parts[2::2]):
        residues.append((name, ops(body)))

    na = region(text, "static void CreateNucleicAcid", "static void CreatePCap3")
    parts = re.split(r"case '(\w)':", na[na.index("switch (na[2])") :])
    bases = [(base, ops(body)) for base, body in zip(parts[1::2], parts[2::2])]

    lines = [
        "//! Residue tables for the sequence parsers.",
        "//!",
        "//! Generated by `tools/gen_sequence_tables.py` from RDKit",
        "//! `Code/GraphMol/FileParsers/SequenceParsers.cpp` (2026.09.1); do not edit.",
        "//!",
        "//! Copyright (C) 2015,2016 Greg Landrum and NextMove Software.",
        "//! Licensed under the BSD 3-Clause license (see LICENSES/RDKit-BSD-3-Clause.txt).",
        "",
        "use super::sequence_parser::{Op, Op::*, Slot::*};",
        "use crate::graphmol::atom::ChiralType::{TetrahedralCCW as CCW, TetrahedralCW as CW};",
        "",
        "/// The amino acids by three letter PDB code, in upstream's order.",
        "pub(super) static AMINO_ACIDS: &[(&str, &[Op])] = &[",
    ]
    for name, o in residues:
        lines.append(f'    ("{name}", &[\n{emit(o)}\n    ]),')
    lines += [
        "];",
        "",
        "/// The base specific part of the nucleotides, keyed by the one letter code.",
        "pub(super) static NUCLEIC_BASES: &[(u8, &[Op])] = &[",
    ]
    for base, o in bases:
        lines.append(f"    (b'{base}', &[\n{emit(o)}\n    ]),")
    lines.append("];")
    monomers = helm_peptide_monomers(text)
    lines += [
        "",
        "/// The HELM peptide monomer ids (`[Abu]`, `[dA]`, ...) and the residue each stands for.",
        "pub(super) static HELM_PEPTIDE_MONOMERS: &[(&str, &str)] = &[",
    ]
    lines += [f'    ("{ident}", "{code}"),' for ident, code in monomers]
    lines.append("];")
    writer = WRITER_SRC.read_text()
    body = region(writer, "static const char *getHELMAAMonomer", "static bool IsEupeptideBond")
    writes = re.findall(r'strcmp\(ptr, "(\w+)"\)\) \{\s*return "([^"]+)";', body)
    lines += [
        "",
        "/// The HELM monomer written for a residue (`getHELMAAMonomer`).",
        "pub(super) static HELM_PEPTIDE_WRITER: &[(&str, &str)] = &[",
    ]
    lines += [f'    ("{res}", "{mono}"),' for res, mono in writes]
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(residues)} residues, {len(bases)} bases, {len(monomers)} HELM monomers")


if __name__ == "__main__":
    main()
