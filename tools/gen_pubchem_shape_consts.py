#!/usr/bin/env python3
"""Writes crates/rdoxide/src/external/pubchem_shape/consts.rs from shape_constants.hpp of pubchem-align3d (daefab3).

    python3 tools/gen_pubchem_shape_consts.py PATH/shape_constants.hpp > crates/rdoxide/src/external/pubchem_shape/consts.rs
"""
import re
import sys

text = open(sys.argv[1]).read()
env = {"qrot1": 0.977659114061, "qrot": 0.210196709523, "qmval": 0.707106781187,
       "drot1": 0.911634686611, "drot2": 0.411001457621}


def table(name):
    m = re.search(r"const double\s+%s((?:\[[^\]]*\])+) = \{" % name, text)
    dims = re.findall(r"\[([^\]]*)\]", m.group(1))
    start = m.end() - 1
    depth, k = 0, start
    while True:
        if text[k] == "{":
            depth += 1
        elif text[k] == "}":
            depth -= 1
            if depth == 0:
                break
        k += 1
    body = re.sub(r"//[^\n]*", "", text[start:k + 1])
    body = body.replace("{", "[").replace("}", "]")
    return eval(body, {}, env), dims


def pad(v, dims):
    """pads the innermost rows with zeros as C does for partial initializers"""
    if len(dims) == 1:
        return [float(x) for x in v] + [0.0] * (dims[0] - len(v))
    return [pad(x, dims[1:]) for x in v]


def emit(v, dims, depth, name=None):
    ind = "    " * depth
    if len(dims) == 1:
        return ind + "[" + ", ".join(repr(x) for x in v) + "],\n"
    out = ind + "[\n"
    for x in v:
        out += emit(x, dims[1:], depth + 1)
    return out + ind + "],\n"


print("// @generated by tools/gen_pubchem_shape_consts.py from pubchem-align3d shape_constants.hpp (public domain, NCBI)")
print("// the values are the truncated decimals of the C++ source, not the mathematical constants\n#![allow(clippy::approx_constant)]\n")
for name, const in (("qmatrix_typed", "QMATRIX"), ("matrix_typed", "MATRIX"), ("pqmatrix_typed", "PQMATRIX"), ("pmatrix_typed", "PMATRIX")):
    v, dims = table(name)
    dims = [int(d) for d in dims]
    v = pad(v, dims)
    ty = "f64"
    for d in reversed(dims):
        ty = "[%s; %d]" % (ty, d)
    body = emit(v, dims, 0).rstrip(",\n")
    print("pub static %s: %s = %s;\n" % (const, ty, body))
