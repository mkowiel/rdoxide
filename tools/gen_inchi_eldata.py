"""Generates crates/rdoxide/src/external/inchi/el_data.rs from the `ElData`
table of InChI's util.c (upstream/external/InChI). The Rust file is checked
in; run this after changing the pinned InChI version."""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "upstream/external/InChI/INCHI_BASE/src/util.c"
OUT = ROOT / "crates/rdoxide/src/external/inchi/el_data.rs"


def main():
    text = SRC.read_text()
    start = text.index("const ELDATA ElData[] =")
    end = text.index("const int ERR_ELEM")
    table = text[start:end]
    # the INCHI_ZFRAG pseudo-elements are not compiled
    table = re.sub(r"#ifdef INCHI_ZFRAG.*?#endif", "", table, flags=re.S)
    rows = []
    row_re = re.compile(
        r'\{\s*"(\w*)",\s*(\d+),\s*(\d+),\s*([\d.]+),\s*(METAL2|METAL|0)\s*,\s*(\d+),\s*(\d+),\s*\{(.*?)\}\s*\},?\s*(?:/\*.*?\*/)?\s*$',
        re.M,
    )
    for m in row_re.finditer(table):
        name, mass, norm, exact, typ, neg, skip, vals = m.groups()
        groups = re.findall(r"\{([^{}]*)\}", "{" + vals + "}")
        # vals = "{0,}, {0,}, {1,}, {0,}, {0,}": five groups of up to five valences
        groups = re.findall(r"\{([^{}]*)\}", vals if vals.startswith("{") else "{" + vals)
        assert len(groups) == 5, (name, vals)
        val = []
        for g in groups:
            nums = [int(x) for x in g.replace(" ", "").split(",") if x != ""]
            assert len(nums) <= 5
            val.append(nums + [0] * (5 - len(nums)))
        rows.append((name, int(mass), int(norm), exact, typ, int(neg), int(skip), val))
    assert rows[0][0] == "H" and rows[-1][0] == "", rows[-1]
    out = [
        "//! The `ElData` table of InChI (`INCHI_BASE/src/util.c`): symbols, masses,",
        "//! element types and the valences of the ions and the neutral atoms.",
        "//!",
        "//! Generated by `tools/gen_inchi_eldata.py`; do not edit.",
        "//!",
        "//! International Chemical Identifier (InChI), Version 1, Software version 1.07.",
        "//! Copyright (c) 2024 IUPAC and InChI Trust.",
        "//! Licensed under the MIT license (see LICENSES/InChI-MIT.txt).",
        "",
        "use super::incomdef::{METAL, METAL2};",
        "",
        "/// `METAL`, `METAL2` (`incomdef.h`) or 0",
        "pub type ElType = i32;",
        "",
        "/// `ELDATA`",
        "#[derive(Debug, Clone, Copy)]",
        "pub struct ElData {",
        "    pub name: &'static str,",
        "    pub at_mass: i32,",
        "    pub norm_at_mass: i32,",
        "    pub exact_mass: f64,",
        "    pub el_type: ElType,",
        "    pub el_neg_pauling10: i32,",
        "    pub skip_adding_h: bool,",
        "    /// valences for the charges -2..=2",
        "    pub valence: [[i8; 5]; 5],",
        "}",
        "",
        "pub static EL_DATA: [ElData; %d] = [" % len(rows),
    ]
    for name, mass, norm, exact, typ, neg, skip, val in rows:
        t = {"0": "0", "METAL": "METAL", "METAL2": "METAL2"}[typ]
        out.append(
            f'    ElData {{ name: "{name}", at_mass: {mass}, norm_at_mass: {norm}, exact_mass: {exact}, el_type: {t}, '
            f"el_neg_pauling10: {neg}, skip_adding_h: {'true' if skip else 'false'}, valence: {val} }},"
        )
    out.append("];")
    OUT.write_text("\n".join(out) + "\n")
    print(len(rows), "rows ->", OUT)


main()
