#!/usr/bin/env python3
"""Audit the licenses of the Rust crates rdoxide depends on.

Reads `cargo metadata` and

* fails if a dependency's SPDX license expression is not covered by ALLOWED,
* checks that LICENSES/CRATES.md lists exactly the current dependencies
  (regenerate it with `--write` after changing Cargo.lock).

Only the Python standard library and cargo are needed. Run from anywhere:

    python tools/check_licenses.py           # CI mode
    python tools/check_licenses.py --write   # refresh LICENSES/CRATES.md
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / "LICENSES" / "CRATES.md"

# Permissive licenses compatible with distributing rdoxide under its own
# (BSD-3-Clause AND MIT AND Apache-2.0 WITH LLVM-exception) terms. Anything else
# (GPL, LGPL, MPL, unknown, ...) needs a deliberate decision and a new entry.
ALLOWED = {
    "0BSD",
    "Apache-2.0",
    "Apache-2.0 WITH LLVM-exception",
    "BSD-2-Clause",
    "BSD-3-Clause",
    "CC0-1.0",
    "ISC",
    "MIT",
    "Unicode-3.0",
    "Unlicense",
    "Zlib",
}

HEADER = """\
# Rust crate dependencies

Generated by `tools/check_licenses.py --write`; CI fails if it is out of date or
a crate carries a license that is not on the allow-list in that script.
The licenses of code translated from RDKit and other upstream projects are
listed in `README.md` in this directory.

| Crate | Version | License |
|-------|---------|---------|
"""


def cargo_metadata() -> dict:
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked"],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return json.loads(out)


def tokenize(expr: str) -> list[str]:
    return re.findall(r"\(|\)|[^\s()]+", expr.replace("/", " OR "))


def evaluate(tokens: list[str], pos: int = 0) -> tuple[bool, int]:
    """SPDX expression -> (is every required license allowed?, next position).

    `A OR B` is satisfied by either side, `A AND B` needs both, and
    `A WITH E` is looked up as the combined string.
    """

    def term(i: int) -> tuple[bool, int]:
        if tokens[i] == "(":
            ok, i = evaluate(tokens, i + 1)
            return ok, i + 1  # skip ")"
        name = tokens[i]
        i += 1
        if i < len(tokens) and tokens[i] == "WITH":
            name = f"{name} WITH {tokens[i + 1]}"
            i += 2
        return name.rstrip("+") in ALLOWED, i

    def conjunction(i: int) -> tuple[bool, int]:
        ok, i = term(i)
        while i < len(tokens) and tokens[i] == "AND":
            rhs, i = term(i + 1)
            ok = ok and rhs
        return ok, i

    ok, i = conjunction(pos)
    while i < len(tokens) and tokens[i] == "OR":
        rhs, i = conjunction(i + 1)
        ok = ok or rhs
    return ok, i


def dependencies(meta: dict) -> list[dict]:
    workspace = set(meta["workspace_members"])
    deps = [p for p in meta["packages"] if p["id"] not in workspace]
    return sorted(deps, key=lambda p: (p["name"], p["version"]))


def render(deps: list[dict]) -> str:
    rows = [f"| {p['name']} | {p['version']} | {p['license'] or 'UNKNOWN'} |\n" for p in deps]
    return HEADER + "".join(rows)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--write", action="store_true", help="rewrite LICENSES/CRATES.md")
    args = ap.parse_args()

    deps = dependencies(cargo_metadata())
    bad = [p for p in deps if not p["license"] or not evaluate(tokenize(p["license"]))[0]]
    for p in bad:
        print(f"license not allowed: {p['name']} {p['version']}: {p['license']!r}", file=sys.stderr)

    table = render(deps)
    if args.write:
        TABLE.write_text(table)
        print(f"wrote {TABLE.relative_to(ROOT)} ({len(deps)} crates)")
    elif not TABLE.exists() or TABLE.read_text() != table:
        print(
            "LICENSES/CRATES.md is out of date; run `python tools/check_licenses.py --write`",
            file=sys.stderr,
        )
        return 1
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
