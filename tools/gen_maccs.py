#!/usr/bin/env python3
"""Generate crates/rdoxide/src/graphmol/fingerprints/maccs.rs from upstream
Code/GraphMol/Fingerprints/MACCS.cpp (pattern table + substructure-match bit
rules; the atom-type switch and bits 125/166 are emitted from the same
source by simple rewriting)."""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "upstream/rdkit/Code/GraphMol/Fingerprints/MACCS.cpp"
OUT = ROOT / "crates/rdoxide/src/graphmol/fingerprints/maccs.rs"


def main() -> None:
    text = SRC.read_text()
    pats = []
    for m in re.finditer(r"bit_(\d+)\s*=\s*std::unique_ptr<\s*RDKit::ROMol>\(\s*RDKit::SmartsToMol\(\s*((?:\"[^\"]*\"\s*)+)\)\);", text):
        smarts = "".join(re.findall(r'"([^"]*)"', m.group(2)))
        pats.append((int(m.group(1)), smarts))
    # atom-type switch
    sw = text[text.index("switch (atom->getAtomicNum())"):text.index("std::vector<RDKit::MatchVectType> matches;") if False else text.index("if (RDKit::SubstructMatch(mol, *pats.bit_8,")]
    arms = []
    cases = []
    for line in sw.splitlines():
        line = line.strip()
        if m := re.match(r"case (\d+):", line):
            cases.append(m.group(1))
        elif m := re.match(r"fp\.setBit\((\d+)\);", line):
            arms.append((tuple(cases), m.group(1)))
        elif line == "break;":
            cases = []
    arm_map: dict[tuple, list] = {}
    for c, b in arms:
        arm_map.setdefault(c, []).append(b)
    # substructure rules
    body = text[text.index("if (RDKit::SubstructMatch(mol, *pats.bit_8,"):text.index("/* BIT 125 */")]
    rules = []
    for line in body.splitlines():
        s = line.strip()
        if not s or s == "}":
            if s == "}":
                rules.append("}")
            continue
        if m := re.fullmatch(r"if \(RDKit::SubstructMatch\(mol, \*pats\.bit_(\d+), match, true\)\) \{", s):
            rules.append(f"if has({m.group(1)})? {{")
        elif m := re.fullmatch(r"if \(RDKit::SubstructMatch\(mol, \*pats\.bit_(\d+), matches, true, true\) > (\d+)\) \{", s):
            rules.append(f"if count({m.group(1)})? > {m.group(2)} {{")
        elif m := re.fullmatch(r"count = RDKit::SubstructMatch\(mol, \*pats\.bit_(\d+), matches, true, true\);", s):
            rules.append(f"let n = count({m.group(1)})?;")
        elif m := re.fullmatch(r"if \(count > (\d+)\) \{", s):
            rules.append(f"if n > {m.group(1)} {{")
        elif m := re.fullmatch(r"fp\.setBit\((\d+)\);", s):
            rules.append(f"set({m.group(1)});")
        else:
            sys.exit(f"unhandled line: {s}")
    out = []
    w = out.append
    w("//! MACCS keys (upstream `GraphMol/Fingerprints/MACCS.cpp`).")
    w("//!")
    w("//! GENERATED by `tools/gen_maccs.py` from the upstream source; do not edit.")
    w("")
    w("#![allow(clippy::manual_range_patterns)] // case lists mirror the upstream switch")
    w("")
    w("use crate::datastructs::{BitVect, ExplicitBitVect};")
    w("use crate::error::{RDKitError, Result};")
    w("use crate::graphmol::romol::ROMol;")
    w("use crate::graphmol::smiles_parse::smarts::{SmartsParserParams, mol_from_smarts};")
    w("use crate::graphmol::substruct::{SubstructMatchParameters, substruct_match};")
    w("")
    w("/// (bit, SMARTS) of the substructure-based keys")
    w("pub const PATTERNS: &[(u32, &str)] = &[")
    for b, s in pats:
        w(f"    ({b}, {s!r}),".replace("'", '"'))
    w("];")
    w("")
    w("fn patterns() -> Result<&'static [Option<ROMol>]> {")
    w("    static PATS: std::sync::OnceLock<Vec<Option<ROMol>>> = std::sync::OnceLock::new();")
    w("    if let Some(p) = PATS.get() {")
    w("        return Ok(p);")
    w("    }")
    w("    let params = SmartsParserParams::default();")
    w("    let mut v: Vec<Option<ROMol>> = (0..167).map(|_| None).collect();")
    w("    for &(bit, sma) in PATTERNS {")
    w("        v[bit as usize] = Some(mol_from_smarts(sma, &params)?.ok_or_else(|| RDKitError::invariant(\"bad MACCS smarts\"))?);")
    w("    }")
    w("    Ok(PATS.get_or_init(|| v))")
    w("}")
    w("")
    w("/// `MACCSFingerprints::getFingerprintAsBitVect`")
    w("pub fn get_fingerprint_as_bit_vect(mol: &ROMol) -> Result<ExplicitBitVect> {")
    w("    let mut fp = ExplicitBitVect::new(167, false);")
    w("    if mol.num_atoms() == 0 {")
    w("        return Ok(fp);")
    w("    }")
    w("    let pats = patterns()?;")
    w("    let one = SubstructMatchParameters { max_matches: 1, ..Default::default() };")
    w("    let all = SubstructMatchParameters::default();")
    w("    let query = |b: u32| pats[b as usize].as_ref().expect(\"pattern defined\");")
    w("    let has = |b: u32| -> Result<bool> { Ok(!substruct_match(mol, query(b), &one)?.is_empty()) };")
    w("    let count = |b: u32| -> Result<usize> { Ok(substruct_match(mol, query(b), &all)?.len()) };")
    w("    let mut bits: Vec<u32> = Vec::new();")
    w("    let mut set = |b: u32| bits.push(b);")
    w("    for i in 0..mol.num_atoms() {")
    w("        match mol.atom(i).atomic_num() {")
    for cases, bs in arm_map.items():
        w(f"            {' | '.join(cases)} => {{")
        for b in bs:
            w(f"                set({b});")
        w("            }")
    w("            _ => {}")
    w("        }")
    w("    }")
    indent = 1
    for r in rules:
        if r == "}":
            indent -= 1
        w("    " * indent + r)
        if r.endswith("{"):
            indent += 1
    w("    // BIT 125: more than one aromatic ring")
    w("    let mut n_arom = 0;")
    w("    for ring in mol.ring_info().bond_rings() {")
    w("        if ring.iter().all(|&b| mol.bond(b as u32).is_aromatic()) {")
    w("            if n_arom > 0 {")
    w("                set(125);")
    w("                break;")
    w("            }")
    w("            n_arom += 1;")
    w("        }")
    w("    }")
    w("    // BIT 166: more than one fragment")
    w("    if crate::graphmol::mol_ops::frags::get_mol_frags_mapping(mol).0 > 1 {")
    w("        set(166);")
    w("    }")
    w("    for b in bits {")
    w("        fp.set_bit(b)?;")
    w("    }")
    w("    Ok(fp)")
    w("}")
    OUT.write_text("\n".join(out) + "\n")
    print(f"{len(pats)} patterns, {len(rules)} rule lines -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
