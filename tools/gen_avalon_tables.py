#!/usr/bin/env python3
"""Generates crates/rdoxide/src/external/avalon/tables.rs from the Avalon Toolkit sources
(`ptable` and `periodic_table` of utilities.c).

    python3 tools/gen_avalon_tables.py <path to src/main/C/common/utilities.c>
"""
import re
import sys

src = open(sys.argv[1], errors="replace").read()
a = src.index("struct ptable_entry ptable[] =")
b = src.index("};", a)
pt = re.findall(r'\{\s*"([^"]+)"\s*,\s*(-?\d+)\s*,\s*([-\d.]+)\s*,\s*([-\d.]+)\s*,\s*([-\d.]+)\s*\}', src[a:b])
a = src.index("string_int_table periodic_table[] =")
b = src.index("};", a)
st = re.findall(r'\{\s*"([^"]+)"\s*,\s*(-?\d+)\s*\}', src[a:b])
out = ["// generated by tools/gen_avalon_tables.py from Avalon Toolkit utilities.c; do not edit",
       "// Copyright 2001-2011 Novartis Pharma AG (see LICENSES/Avalon-BSD-3-Clause-Novartis.txt)",
       "", "/// `struct ptable_entry`: symbol, common valence, average mass, electronegativity, heat of formation",
       "pub const PTABLE: &[(&str, i32, f32, f32, f32)] = &["]
for s, v, m, e, h in pt:
    out.append(f'    ("{s}", {v}, {float(m)!r}, {float(e)!r}, {float(h)!r}),')
out += ["];", "", "/// `periodic_table` (symbol, atomic number)", "pub const PERIODIC_TABLE: &[(&str, i32)] = &["]
for s, v in st:
    out.append(f'    ("{s}", {v}),')
out.append("];")
print("\n".join(out))
