@pytest.mark.parametrize("cxsmiles,expected", ATROPISOMERS)
def test_atropisomer_labels(cxsmiles, expected):
    ps = Chem.SmilesParserParams()
    ps.allowCXSMILES = True
    ps.parseName = False
    ps.removeHs = False
    mol = Chem.MolFromSmiles(cxsmiles, ps)
    assert mol is not None
    rdCIPLabeler.AssignCIPLabels(mol)
    codes = "".join(
        f"{b.GetBeginAtomIdx()}-{b.GetEndAtomIdx()}={b.GetProp('_CIPCode')}:"
        for b in mol.GetBonds() if b.HasProp("_CIPCode") and b.GetBondType() == Chem.BondType.SINGLE)
    assert codes == expected
